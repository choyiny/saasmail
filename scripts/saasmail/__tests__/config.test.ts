import { readFileSync } from "node:fs";
import { parse, type ParseError } from "jsonc-parser";
import { describe, expect, it } from "vitest";
import { createHash } from "node:crypto";
import {
  ConfigConflict,
  configHash,
  deployedPart,
  generateWranglerConfig,
  isGenerated,
} from "../config.ts";
import { resourceNames } from "../names.ts";
import { newState, type InstallState, type Provider } from "../state.ts";

const template = readFileSync(
  new URL("../../../wrangler.jsonc.example", import.meta.url),
  "utf8",
);

function fixture(
  hostname: string | null = "mail.example.com",
  provider: Provider = "cloudflare",
): InstallState {
  const s = newState({
    installationId: "acme-1a2b3c4d5e6f",
    accountId: "a".repeat(32),
    inputs: {
      name: "acme",
      hostname,
      workersDev: hostname === null,
      inboundDomains: ["in.example.org"],
      provider,
      sendDomains: ["send.example.net"],
      cookiePrefix: "acme",
    },
    names: resourceNames("acme"),
    baseUrl: hostname ? `https://${hostname}` : "https://acme.me.workers.dev",
  });
  s.resources.push({
    key: "d1",
    kind: "d1",
    name: "acme-db",
    id: "d1-uuid-1234",
    ownership: "created",
    state: "ready",
  });
  return s;
}

const extra = {
  version: "1.2.3",
  existing: null,
  command: "yarn saasmail install",
  build: null,
};

function read(text: string) {
  const errors: ParseError[] = [];
  const v = parse(text, errors) as Record<string, any>;
  expect(errors).toEqual([]);
  return v;
}

describe("generated marker", () => {
  it("old marker still counts as generated", () => {
    const old =
      "// Generated by yarn saasmail install (x). Edit inputs with yarn saasmail, not by hand.\n{}\n";
    expect(isGenerated(old)).toBe(true);
    expect(() =>
      generateWranglerConfig(template, fixture(), { ...extra, existing: old }),
    ).not.toThrow(ConfigConflict);
  });
});

describe("generateWranglerConfig", () => {
  it("sets every field from the state", () => {
    const s = fixture();
    s.vapidPublicKey = "PUBKEY";
    const text = generateWranglerConfig(template, s, extra);
    const c = read(text);
    expect(text.split("\n")[0]).toBe(
      "// Generated by saasmail (acme-1a2b3c4d5e6f). Edit inputs with yarn saasmail install, not by hand.",
    );
    expect(c.name).toBe("acme");
    expect(c.account_id).toBe(s.accountId);
    expect(c.d1_databases[0]).toMatchObject({
      binding: "DB",
      database_name: "acme-db",
      database_id: "d1-uuid-1234",
    });
    expect(c.r2_buckets[0]).toMatchObject({
      binding: "R2",
      bucket_name: "acme-attachments",
    });
    expect(c.queues.producers[0]).toEqual({
      binding: "EMAIL_QUEUE",
      queue: "acme-sequence-emails",
    });
    expect(c.queues.consumers[0].queue).toBe("acme-sequence-emails");
    expect(c.queues.consumers[0].max_batch_size).toBe(10);
    expect(c.workflows[0]).toMatchObject({
      binding: "GMAIL_BACKFILL",
      name: "acme-gmail-backfill",
    });
    expect(c.routes).toEqual([
      { pattern: "mail.example.com", custom_domain: true },
    ]);
    expect(c.send_email).toEqual([{ name: "EMAIL" }]);
    expect(c.email_routing).toBeUndefined();
    expect(c.vars).toMatchObject({
      BASE_URL: "https://mail.example.com",
      TRUSTED_ORIGINS: "https://mail.example.com",
      COOKIE_PREFIX: "acme",
      VAPID_PUBLIC_KEY: "PUBKEY",
      VAPID_SUBJECT: "mailto:admin@mail.example.com",
      SAASMAIL_VERSION: "1.2.3",
    });
    expect(c.vars.addresses).toBeUndefined();
    expect(c.addresses).toBeUndefined();
  });

  it("writes SAASMAIL_INSTALLATION as a JSON string", () => {
    const s = fixture();
    const c = read(generateWranglerConfig(template, s, extra));
    expect(typeof c.vars.SAASMAIL_INSTALLATION).toBe("string");
    expect(JSON.parse(c.vars.SAASMAIL_INSTALLATION)).toEqual({
      installationId: s.installationId,
      ownershipNonce: s.ownershipNonce,
    });
  });

  it("is byte-identical for the same inputs", () => {
    const s = fixture();
    expect(generateWranglerConfig(template, s, extra)).toBe(
      generateWranglerConfig(template, s, extra),
    );
  });

  it("workers.dev install has no routes; empty VAPID key; subject from a domain", () => {
    const c = read(generateWranglerConfig(template, fixture(null), extra));
    expect(c.routes).toBeUndefined();
    expect(c.vars.VAPID_PUBLIC_KEY).toBe("");
    expect(c.vars.VAPID_SUBJECT).toBe("mailto:admin@send.example.net");
    expect(c.vars.BASE_URL).toBe("https://acme.me.workers.dev");
  });

  it("subject falls back to an inbound domain, then to the base URL's host", () => {
    const s = fixture(null, "resend");
    s.inputs.sendDomains = [];
    expect(
      read(generateWranglerConfig(template, s, extra)).vars.VAPID_SUBJECT,
    ).toBe("mailto:admin@in.example.org");
    s.inputs.inboundDomains = [];
    expect(
      read(generateWranglerConfig(template, s, extra)).vars.VAPID_SUBJECT,
    ).toBe("mailto:admin@acme.me.workers.dev");
  });

  it("a subject frozen in the state wins over the domains", () => {
    const s = fixture(null);
    s.vapidSubject = "mailto:admin@acme.me.workers.dev";
    s.inputs.sendDomains = ["new.example.com"];
    expect(
      read(generateWranglerConfig(template, s, extra)).vars.VAPID_SUBJECT,
    ).toBe("mailto:admin@acme.me.workers.dev");
  });

  it("send_email only for the cloudflare provider", () => {
    for (const p of ["resend", "postmark", "bavimail", "none"] as const) {
      const c = read(generateWranglerConfig(template, fixture(null, p), extra));
      expect(c.send_email).toBeUndefined();
    }
    // and removed if the template had it
    const withSend = template.replace(
      '  // "send_email": [\n  //   { "name": "EMAIL" }\n  // ],',
      '  "send_email": [{ "name": "EMAIL" }],',
    );
    expect(withSend).not.toBe(template);
    expect(
      read(generateWranglerConfig(withSend, fixture(null, "resend"), extra))
        .send_email,
    ).toBeUndefined();
  });

  it("refuses a hand-written wrangler.jsonc", () => {
    expect(() =>
      generateWranglerConfig(template, fixture(), {
        ...extra,
        existing: '{ "name": "mine" }',
      }),
    ).toThrow(ConfigConflict);
  });

  it("keeps the env block of an existing generated file", () => {
    const base = generateWranglerConfig(template, fixture(), extra);
    const withEnv = base.replace(
      /\n}\s*$/,
      ',\n  "env": { "dev": { "vars": { "COOKIE_PREFIX": "mine" } } }\n}\n',
    );
    expect(read(withEnv).env).toBeDefined();
    const c = read(
      generateWranglerConfig(template, fixture(), {
        ...extra,
        existing: withEnv,
      }),
    );
    expect(c.env.dev.vars.COOKIE_PREFIX).toBe("mine");
  });

  it("renames the consumer of the producer's queue, wherever it is listed", () => {
    const other = '{ "queue": "other-queue", "max_retries": 1 },\n      ';
    const t2 = template.replace(
      '"consumers": [\n      {',
      `"consumers": [\n      ${other}{`,
    );
    expect(t2).not.toBe(template);
    const c = read(generateWranglerConfig(t2, fixture(), extra));
    expect(c.queues.consumers.map((x: any) => x.queue)).toEqual([
      "other-queue",
      "acme-sequence-emails",
    ]);
    expect(() =>
      generateWranglerConfig(
        template.replace(
          '"queue": "saasmail-sequence-emails",\n        "max_batch',
          '"queue": "x",\n        "max_batch',
        ),
        fixture(),
        extra,
      ),
    ).toThrow(/consumer/);
  });

  it("keeps template comments below the header", () => {
    const text = generateWranglerConfig(template, fixture(), extra);
    expect(text).toContain("// Outbound email provider selection");
  });

  it("fails clearly when a binding is missing from the template", () => {
    expect(() =>
      generateWranglerConfig(
        template.replace('"binding": "R2"', '"binding": "OTHER"'),
        fixture(),
        extra,
      ),
    ).toThrow(/binding "R2"/);
  });
});

describe("isGenerated / deployedPart", () => {
  it("checks the first line", () => {
    expect(
      isGenerated(generateWranglerConfig(template, fixture(), extra)),
    ).toBe(true);
    expect(isGenerated(template)).toBe(false);
  });
  it("deployedPart ignores the env block", () => {
    const base = generateWranglerConfig(template, fixture(), extra);
    const a = base.replace(/\n}\s*$/, ',\n  "env": { "dev": {} }\n}\n');
    const b = base.replace(/\n}\s*$/, ',\n  "env": { "dev": { "x": 1 } }\n}\n');
    expect(deployedPart(a)).toBe(deployedPart(b));
    expect(parse(deployedPart(a)).env).toBeUndefined();
  });
});

describe("package build paths", () => {
  const build = (p: string) => ({
    main: `${p}/worker/index.js`,
    assetsDir: `${p}/client`,
    migrationsDir: `${p}/migrations`,
    moduleConfig: {
      no_bundle: true,
      rules: [{ type: "ESModule", globs: ["**/*.js"] }],
    },
  });

  it("package build paths are written", () => {
    const c = read(
      generateWranglerConfig(template, fixture(), {
        ...extra,
        build: build("/p"),
      }),
    );
    expect(c.main).toBe("/p/worker/index.js");
    expect(c.no_bundle).toBe(true);
    expect(c.rules).toEqual([{ type: "ESModule", globs: ["**/*.js"] }]);
    expect(c.assets.directory).toBe("/p/client");
    expect(c.assets.binding).toBe("ASSETS");
    expect(c.d1_databases[0].migrations_dir).toBe("/p/migrations");
  });

  it("package path change is not drift", () => {
    const state = fixture();
    const render = (p: string, version = "1.2.3") =>
      generateWranglerConfig(template, state, {
        ...extra,
        version,
        build: build(p),
      });
    expect(configHash(render("/p"), build("/p"))).toBe(
      configHash(render("/q"), build("/q")),
    );
    expect(configHash(render("/p"), build("/p"))).not.toBe(
      configHash(render("/p", "1.2.4"), build("/p")),
    );
  });

  it("checkout hash unchanged", () => {
    const text = generateWranglerConfig(template, fixture(), extra);
    expect(configHash(text, null)).toBe(
      createHash("sha256").update(deployedPart(text)).digest("hex"),
    );
  });
});
